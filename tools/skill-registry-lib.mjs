// Reads the pinned obsidian-agent registry into Companion's generated skill list. Shared by build, verify, and the drift test.
import { readFileSync } from "node:fs";
import path from "node:path";

const SUB_SKILL = /^\*\*REQUIRED SUB-SKILL:\*\*\s*obsidian-agent:([a-z0-9-]+)\s*$/gm;

function stripFrontmatter(markdown) {
  const m = /^---\n[\s\S]*?\n---\n?/.exec(markdown);
  return (m ? markdown.slice(m[0].length) : markdown).trim();
}

function included(cap) {
  return cap.portable === true && cap.surfaces?.skill === true && cap.surfaces?.command !== false;
}

export function buildSkillEntries(pluginDir) {
  const registry = JSON.parse(readFileSync(path.join(pluginDir, "capabilities.json"), "utf8"));
  const bodies = new Map();
  for (const cap of registry.capabilities) {
    try {
      bodies.set(cap.id, stripFrontmatter(readFileSync(path.join(pluginDir, "skills", cap.id, "SKILL.md"), "utf8")));
    } catch {
      // A capability without a SKILL.md is not a skill.
    }
  }
  const names = new Map(registry.capabilities.map((c) => [c.id, c.name]));

  // Sub-skill bodies carry their own directives; resolve transitively, each id once per entry.
  function resolve(own, seen) {
    const directIds = [];
    const body = own.replace(SUB_SKILL, (_, id) => {
      directIds.push(id);
      return "";
    }).trim();
    const appended = [];
    for (const id of directIds) {
      if (seen.has(id)) continue;
      seen.add(id);
      const sub = bodies.get(id);
      if (sub === undefined) {
        appended.push(`Sub-skill ${id} is not available in Companion.`);
        continue;
      }
      const nested = resolve(sub, seen);
      appended.push(`## Included skill: ${names.get(id) ?? id}\n\n${nested.body}`, ...nested.appended);
    }
    return { body, appended };
  }

  const entries = [];
  for (const cap of registry.capabilities) {
    if (!included(cap)) continue;
    const own = bodies.get(cap.id);
    if (own === undefined) continue;
    const { body, appended } = resolve(own, new Set([cap.id]));
    entries.push({
      id: cap.id,
      name: cap.name,
      description: cap.description,
      tier: cap.tier,
      argHint: typeof cap.surfaces.command === "string" ? cap.surfaces.command : "",
      body: [body, ...appended].join("\n\n"),
    });
  }
  return entries;
}

export function renderRegistry(entries) {
  const lines = [
    "// GENERATED by tools/build-skill-registry.mjs from claude-plugin/capabilities.json and skills/*/SKILL.md. Do not edit.",
    "",
    "export interface SkillEntry {",
    "  id: string;",
    "  name: string;",
    "  description: string;",
    "  tier: string;",
    "  /** Argument hint from the registry's command surface; empty when the skill takes none. */",
    "  argHint: string;",
    "  /** SKILL.md body without frontmatter; required sub-skills inlined once. */",
    "  body: string;",
    "}",
    "",
    "export const SKILLS: SkillEntry[] = " + JSON.stringify(entries, null, 2) + ";",
    "",
  ];
  return lines.join("\n");
}
